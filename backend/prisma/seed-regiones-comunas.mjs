async function main() {
  console.log('🌎 Insertando regiones de Chile...')
  let regionesInserted = 0
  for (const r of REGIONES) {
    await prisma.region.upsert({
      where: { codigo: r.codigo },
      update: { nombre: r.nombre, activo: true },
      create: { codigo: r.codigo, nombre: r.nombre, activo: true },
    })
    regionesInserted++
  }
  console.log(`✅ ${regionesInserted} regiones insertadas/actualizadas`)

  console.log('🏘️  Insertando comunas de Chile...')
  let comunasInserted = 0
  for (const c of COMUNAS) {
    await prisma.comuna.upsert({
      where: { codigoComuna: c.codigoComuna },
      update: { nombre: c.nombre, codigoRegion: c.codigoRegion, activo: true },
      create: { codigoComuna: c.codigoComuna, codigoRegion: c.codigoRegion, nombre: c.nombre, activo: true },
    })
    comunasInserted++
  }
  console.log(`✅ ${comunasInserted} comunas insertadas/actualizadas`)
  console.log('🎉 Listo.')
}

main()
  .catch(e => { console.error(e); process.exit(1) })
  .finally(() => prisma.$disconnect())
